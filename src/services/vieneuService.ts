/** Default list (Turbo); use getVieNeuVoices(mode) for the model the user picked. */
export const VIENEU_VOICES: VieNeuVoiceItem[] = VIENEU_TURBO_VOICES;

export const VIENEU_MODE_INFO: Record<VieNeuMode, { label: string; sub: string }> = {
  v3turbo: { label: 'Turbo 48kHz', sub: 'Hay hơn, nặng hơn (chậm gấp đôi, tốn nhiều RAM)' },
  v3nano: { label: 'Nano 24kHz', sub: 'Nhẹ và nhanh, chất lượng thấp hơn' },
};

export function getVieNeuVoices(mode: VieNeuMode): VieNeuVoiceItem[] {
  return mode === 'v3nano' ? VIENEU_NANO_VOICES : VIENEU_TURBO_VOICES;
}

export function getVieNeuVoiceById(id: string): VieNeuVoiceItem | undefined {
  const mode = useSettingsStore.getState().vieneuMode;
  const list = getVieNeuVoices(mode);
  return (
    list.find((v) => v.id === id) ||
    VIENEU_TURBO_VOICES.find((v) => v.id === id) ||
    VIENEU_NANO_VOICES.find((v) => v.id === id)
  );
}

/**
 * Synthesize speech using VieNeu-TTS endpoint
 */
export async function fetchVieNeuTTSBlob(
  text: string,
  voice: string = 'minh_quan',
  rate: number = 1.0,
  pitch: number = 1.0
): Promise<Blob> {
  const cleanText = text.trim();
  if (!cleanText) {
    throw new Error('Text cannot be empty');
  }

  const response = await fetch('/api/tts', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      text: cleanText,
      voice,
      engine: 'vieneu',
      mode: useSettingsStore.getState().vieneuMode,
      rate,
      pitch,
    }),
  });

  if (!response.ok) {
    const errorText = await response.text().catch(() => 'Network error');
    throw new Error(`VieNeu TTS failed (${response.status}): ${errorText}`);
  }

  return await response.blob();
}
